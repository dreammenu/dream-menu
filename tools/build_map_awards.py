"""Split awards.js for the map (17 Nov 2026): the map loads awards-map.js (every award place without its street address
and source link, about half the download) and fetches awards-detail.js only when someone opens an award place.
awards.js stays the source file that the build scripts read. Run after any change to awards.js:
  python3 tools/build_map_awards.py
"""
import json
import re

s = open('awards.js', encoding='utf-8').read()
m = re.search(r'window\.DM_AWARDS\s*=\s*', s)
o = json.JSONDecoder().raw_decode(s[m.end():])[0]
detail = {}
for r in o['places']:
    if r[13] or r[14]:
        detail[r[0]] = [r[13], r[14]]
    r[13] = r[14] = ''
o['meta']['detail'] = '/awards-detail.js'
dump = lambda x: json.dumps(x, ensure_ascii=False, separators=(',', ':'))
open('awards-map.js', 'w', encoding='utf-8').write('/* Generated by tools/build_map_awards.py from awards.js. Do not edit. */\nwindow.DM_AWARDS=' + dump(o) + ';\n')
open('awards-detail.js', 'w', encoding='utf-8').write('/* Generated by tools/build_map_awards.py from awards.js. Do not edit. */\nwindow.DM_AWDET=' + dump(detail) + ';\n')
print('awards-map.js and awards-detail.js:', len(o['places']), 'places,', len(detail), 'with an address or link')
