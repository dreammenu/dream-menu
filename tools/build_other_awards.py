#!/usr/bin/env python3
"""Builds other-awards.js: awards and lists outside awards.js, matched to Dream Menu guest venues.

Inputs (all in tools/data):
  other-awards.json        the lists as collected (Scottish, UK, bar lists, past guide editions, AA Rosettes at all levels)
  other-awards-links.json  hand-reviewed matches of list entries to guest venue ids (rejected look-alikes noted there)
  other-recognition.json   recognition checked by hand venue by venue (by guest venue name)

Output: other-awards.js  window.DM_OA = {meta: {...}, v: {venue_id: [[text, year, list, url], ...]}}
Used by: tools/build_intel.py (critics), tools/build_case_studies.py, tools/build_venue_pages.py, analysis.js.
Entries that repeat an award already shown from awards.js (e.g. a 2025 MICHELIN Bib where 2026 is in awards.js) are skipped.

Run after refresh_static.py and before build_intel.py:  python3 tools/build_other_awards.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)


def load(fn, var):
    s = open(fn, encoding='utf-8').read()
    m = re.search(r'window\.' + var + r'\s*=\s*', s)
    return json.JSONDecoder().raw_decode(s[m.end():])[0]


D = load('dm-data.js', 'DM')
OA = json.load(open('tools/data/other-awards.json', encoding='utf-8'))
LK = json.load(open('tools/data/other-awards-links.json', encoding='utf-8'))['links']
REC = json.load(open('tools/data/other-recognition.json', encoding='utf-8'))
LISTS = {l['code']: l for l in OA['lists']}
BY_NAME = {}
for v in D['venues']:
    BY_NAME.setdefault(v['n'], v['i'])
AW = D.get('aw') or {}

# the award belongs to a bar or restaurant inside the place guests named: say so
AT = {('The American Bar at Gleneagles', 'Gleneagles'): 'The American Bar', ('The Connaught Bar', 'The Connaught'): 'The Connaught Bar',
      ('Number One, The Balmoral', 'The Balmoral'): 'Number One'}
SHORT = {'sbpa': 'Scottish Bar & Pub Awards', 'sltn': 'SLTN Awards', 'sra': 'Scottish Restaurant Awards', 'gba': 'Glasgow Bar Awards',
         'eba': 'Edinburgh Bar Awards', 'sca': 'Scottish Curry Awards', 'aah': 'AA Hospitality Awards', 'ara': "Scotland's Asian Restaurant Awards",
         'class': 'CLASS Bar Awards', 'npba': 'National Pub & Bar Awards', 't50g': 'Top 50 Gastropubs', 'tabob': 'Tripadvisor Best of the Best',
         'sasfa': 'Scottish Asian Food Awards', 'sex': 'Scottish Excellence Awards', 'fas': 'Food Awards Scotland', 'spice': 'Spice Awards',
         'nra': 'National Restaurant Awards'}


def text(L, entry):
    code, y, t = L['code'], L['year'], entry[2]
    fam = code.split('-')[0]
    if t.startswith('#'):
        return f'{t} {y}'
    if fam == 'aa':
        return f'{t} ({y} list)'
    if fam == 'mich':
        return f'{t} {y}'
    if fam == 'gfga':
        return f'Good Food Guide Awards {y}: {t}'
    if fam.startswith('gfg'):
        return f'{t} {y}'
    if fam == 'scran':
        return t
    if fam == 'sra' and t in ('Category winner', 'Outstanding achievement', 'Recognition for excellence'):
        return f'Scottish Restaurant Awards {y}: {t.lower()}'
    return f'{SHORT.get(fam, L["name"])} {y}: {t}'


def dup_of_guides(L, vid):
    labels = ' '.join((AW.get(vid) or {}).get('a', []))
    fam = L['code'].split('-')[0]
    if fam == 'mich' and ('MICHELIN' in labels or 'Bib Gourmand' in labels):
        return True
    if fam == 'aa' and 'AA Rosette' in labels:
        return True
    return False


out = {}
skipped = 0
for lk in LK:
    L = LISTS[lk['list']]
    e = next(x for x in L['entries'] if x[0] == lk['entry'] and x[1] == lk['town'])
    vid = lk['venue']
    if dup_of_guides(L, vid):
        skipped += 1
        continue
    t = text(L, e)
    at = AT.get((lk['entry'], lk['venue_name']))
    if at:
        t = f'{at}: {t}'
    row = [t, L['year'], L['name'], L['url']]
    if row[0] not in [r[0] for r in out.get(vid, [])]:
        out.setdefault(vid, []).append(row)
for name, items in REC['venues'].items():
    vid = BY_NAME.get(name)
    if not vid:
        continue
    for t in items:
        have = ' '.join(r[0] for r in out.get(vid, [])).lower()
        key = re.sub(r'\W+', ' ', t.lower())[:28]
        if key and key in re.sub(r'\W+', ' ', have):
            continue
        out.setdefault(vid, []).append([t, 0, 'Checked by hand', REC.get('sources', {}).get(name, '')])
for vid in out:
    out[vid].sort(key=lambda r: (-r[1], r[0]))
meta = dict(built=__import__('datetime').date.today().isoformat(), lists=len(OA['lists']), entries=sum(len(l['entries']) for l in OA['lists']),
            venues=len(out), awards=sum(len(v) for v in out.values()),
            names=sorted({f"{l['name']} {l['year']}" for l in OA['lists']}))
open('other-awards.js', 'w', encoding='utf-8').write('/* Generated by tools/build_other_awards.py. Awards outside awards.js matched to guest venues. */\nwindow.DM_OA='
                                                    + json.dumps(dict(meta=meta, v=out), ensure_ascii=False, separators=(',', ':')) + ';\n')
print('venues', len(out), 'awards', meta['awards'], 'skipped as already in guides', skipped)
